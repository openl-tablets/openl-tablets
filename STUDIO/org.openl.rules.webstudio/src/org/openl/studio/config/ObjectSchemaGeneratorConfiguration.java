package org.openl.studio.config;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.github.victools.jsonschema.generator.OptionPreset;
import com.github.victools.jsonschema.generator.SchemaGenerator;
import com.github.victools.jsonschema.generator.SchemaGeneratorConfigBuilder;
import com.github.victools.jsonschema.generator.SchemaVersion;
import com.github.victools.jsonschema.module.jackson.JacksonModule;
import com.github.victools.jsonschema.module.swagger2.Swagger2Module;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.context.annotation.Primary;
import org.springframework.context.annotation.Scope;

/**
 * Configuration for JSON Schema generation using victools SchemaGenerator.
 * <p>
 * The SchemaGenerator is configured to properly handle classes generated by
 * {@link org.openl.rules.calc.CustomSpreadsheetResultOpenClass} which have
 * getter methods without backing fields.
 * <p>
 * Two generators are offered. {@link #schemaGenerator} describes the values the run, tests and trace APIs
 * publish. {@link #inputSchemaGenerator} describes the input a table takes and also records the defaults a
 * datatype declares, see {@link DeclaredDefaultsAttributeOverride}.
 */
@Configuration
public class ObjectSchemaGeneratorConfiguration {

    /**
     * Creates a new SchemaGenerator instance configured for the given ObjectMapper.
     * <p>
     * This is a prototype bean - a new instance is created for each injection/lookup. It is the primary generator.
     * A lookup that names no bean gets this one.
     *
     * @param objectMapper the ObjectMapper to use for introspection
     * @return configured SchemaGenerator
     */
    @Bean
    @Primary
    @Scope("prototype")
    public SchemaGenerator schemaGenerator(ObjectMapper objectMapper) {
        return new SchemaGenerator(configBuilder(objectMapper).build());
    }

    /**
     * Creates a SchemaGenerator for the input a table takes.
     * <p>
     * The schema also carries the defaults a datatype declares as the {@code default} of each property.
     * <p>
     * This is a prototype bean - a new instance is created for each injection/lookup.
     *
     * @param objectMapper the ObjectMapper to use for introspection and to write the defaults
     * @return configured SchemaGenerator
     */
    @Bean
    @Scope("prototype")
    public SchemaGenerator inputSchemaGenerator(ObjectMapper objectMapper) {
        var configBuilder = configBuilder(objectMapper);
        configBuilder.forTypesInGeneral()
                .withTypeAttributeOverride(new DeclaredDefaultsAttributeOverride(objectMapper));
        return new SchemaGenerator(configBuilder.build());
    }

    private static SchemaGeneratorConfigBuilder configBuilder(ObjectMapper objectMapper) {
        var configBuilder = new SchemaGeneratorConfigBuilder(objectMapper, SchemaVersion.DRAFT_2020_12, OptionPreset.PLAIN_JSON)
                .with(new JacksonModule())
                .with(new Swagger2Module());
        configBuilder.forTypesInGeneral()
                .withCustomDefinitionProvider(new JacksonBeanSchemaProvider(objectMapper));
        return configBuilder;
    }
}
